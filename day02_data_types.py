# Python supports various data types that allow you to store different kinds of information.
# The most common data types in Python include: int, float, str, bool, list, tuple, dict, set
# 1. Integer (int): Represents whole numbers without a decimal point.
age = 34 # integer
# 2. Float (float): Represents numbers with a decimal point.
cgpa = 8.3 # float
# 3. String (str): Represents a sequence of characters enclosed in quotes.
name = "Vaheeda" # string
# 4. Boolean (bool): Represents a value that can be either True or False.
is_student = True # boolean
# 5. List (list): Represents an ordered collection of items that can be of different types.
fruits = ["apple", "banana", "cherry"] # list
# 6. Tuple (tuple): Represents an ordered collection of items that cannot be changed (immutable).
coordinates = (10.0, 20.0) # tuple
# 7. Dictionary (dict): Represents a collection of key-value pairs.
person = {"name": "Alice", "age": 30, "city": "New York"} # dictionary
# 8. Set (set): Represents an unordered collection of unique items.
unique_numbers = {1, 2, 3, 4, 5} # set
# You can use the type() function to check the data type of a variable.

age = 34
print(age)
print(type(age))

cgpa = 8.3
print(cgpa)
print(type(cgpa))

name = "Vaheeda"
print(name)
print(type(name))

is_student = True # can also be False
print(is_student)
print(type(is_student))
